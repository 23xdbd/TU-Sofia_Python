
# Въвеждаме цяло десетично число от потребителя
number = int(input("Въведете десетично число: "))

# Копираме числото, за да запазим оригиналната му стойност
n = number

# Създаваме празен низ за двоичното представяне
binary = ""

# Проверяваме дали числото е 0
if n == 0:
    binary = "0"

# Повтаряме делението, докато числото стане 0
while n > 0:

    # Намираме остатъка при деление на 2
    remainder = n % 2

    # Добавяме остатъка в началото на двоичния низ
    binary = str(remainder) + binary

    # Делим числото на 2, като запазваме цялата част
    n = n // 2

# Извеждаме двоичното представяне на числото
print("Двоично представяне:", binary)
