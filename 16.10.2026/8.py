a = int(input("Въведи долна граница: "))
b = int(input("Въведи горна граница: "))

broi = 0 #Започваме броенето от 0

for i in range(10): #Повтаряме 10 пъти
    chislo = int(input("Въведи число: "))

    if a <= chislo <= b: #Проверяваме дали числото е в интервала
        broi = broi + 1 #Ако е в интервала, увеличаваме брояча с 1

print("Броят на числата в избрания интервал е:", broi)